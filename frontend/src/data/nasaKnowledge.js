export function searchNASAKnowledge(query) {
  const queryLower = query.toLowerCase();
  const results = [];
  
  for (const [key, entry] of Object.entries(nasaKnowledge)) {
    const relevance = entry.keywords.reduce((score, keyword) => {
      return score + (queryLower.includes(keyword) ? 1 : 0);
    }, 0);
    
    if (relevance > 0) {
      results.push({ ...entry, relevance, key });
    }
  }
  
  results.sort((a, b) => b.relevance - a.relevance);
  return results.slice(0, 2);
}
